package main

import (
	"fmt"
)

type command struct {
	name string
	args []string
}

type commands struct {
	handlers map[string]func(*state, command) error
}

func (c *commands) run(s *state, cmd command) error {
	var handler func(*state, command) error
	var ok bool
	if handler, ok = c.handlers[cmd.name]; !ok {
		return fmt.Errorf("Unknown command!\n")
	}
	err := handler(s, cmd)
	if err != nil {
		return err
	}
	return nil
}

func (c *commands) register(name string, f func(*state, command) error) {
	c.handlers[name] = f
	return
}